import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {deliveryRedirects,htaccessText} from './lib/public-delivery.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const redirects=await deliveryRedirects(root);
await writeFile(new URL('../public/.htaccess',import.meta.url),htaccessText(redirects));
const blog=redirects.filter(({to})=>/^\/(?:en\/|nl\/)?blog\//.test(to));
const rules=blog.flatMap(({from,to})=>[`${from.slice(0,-1)} ${to} 301`,`${from} ${to} 301`]);
await writeFile(new URL('../public/_redirects',import.meta.url),rules.join('\n')+'\n');
console.log('public/.htaccess generated from the legacy inventory and current project routes.');
