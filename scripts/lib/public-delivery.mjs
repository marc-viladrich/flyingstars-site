import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {localizedHref} from '../../src/lib/localized-routes.mjs';
import {readEditorialRecords} from '../seo-fallback-report.mjs';

export async function deliveryRedirects(root) {
  const inventory=JSON.parse(await readFile(path.join(root,'docs/legacy-url-inventory.json'),'utf8'));
  const redirects=inventory.entries.filter(entry=>entry.status==='redirect').map(({path:from,target:to})=>({from,to}));
  for(const project of (await readEditorialRecords(root)).filter(r=>r.id.startsWith('project/') && !r.data.draft && r.data.showcase)) {
    for(const locale of ['de','en','nl']) redirects.push({
      from:localizedHref(`/projekte/${project.id.slice('project/'.length)}/`,locale),
      to:localizedHref(`/${project.data.showcase.route}/`,locale),
    });
  }
  return redirects.sort((a,b)=>a.from.localeCompare(b.from,'en'));
}

const escapeRegex=text=>text.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
export function htaccessText(redirects) {
  const rules=redirects.map(({from,to})=>`RewriteRule ^${escapeRegex(from.slice(1,-1))}/?$ ${to} [R=301,L]`).join('\n');
  return `# Generated by node scripts/generate-public-delivery.mjs. Public static webroot only.
# Never install this file on the separate Node editor subdomain.
Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
# Production convention observed 2026-10-15: HTTPS, apex host.
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} !^flyingstars\\.art$ [NC]
RewriteRule ^ https://flyingstars.art%{REQUEST_URI} [R=301,L,NE]

# Exact legacy mappings and removed project aliases, with optional trailing slash.
${rules}
</IfModule>

<IfModule mod_headers.c>
# Unversioned files can change at the same URL.
Header onsuccess unset Cache-Control
Header always set Cache-Control "public, max-age=3600"
# Keep all Cache-Control decisions in the same context, in override order.
Header always set Cache-Control "no-cache, max-age=0, must-revalidate" "expr=%{CONTENT_TYPE} =~ m#^text/html(?:;|$)#"
# Only hashed Astro build files qualify for immutable, never arbitrary public assets.
Header always set Cache-Control "public, max-age=31536000, immutable" "expr=%{REQUEST_STATUS} < 400 && %{REQUEST_URI} =~ m#^/_astro/[^/]+[._][A-Za-z0-9_-]{8,}\\.[a-zA-Z0-9]+$#"
# Error responses and accidental editor/API paths must not enter a public cache.
Header always set Cache-Control "no-store" "expr=%{REQUEST_STATUS} >= 400 || %{REQUEST_URI} =~ m#^/(editor|api)(/|$)#"
<FilesMatch "(?i)\\.(html?|css|js|mjs|json|xml|svg|txt)$">
Header merge Vary Accept-Encoding
</FilesMatch>
</IfModule>

# Text only. Missing optional compression extensions must not break delivery.
<IfModule mod_filter.c>
<IfModule mod_brotli.c>
AddOutputFilterByType BROTLI_COMPRESS text/html text/plain text/css text/javascript application/javascript application/json application/xml text/xml image/svg+xml
</IfModule>
<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/plain text/css text/javascript application/javascript application/json application/xml text/xml image/svg+xml
</IfModule>
</IfModule>
`;
}
