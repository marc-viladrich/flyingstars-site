import definitions from '../browser-site.mjs';
import {createBrowserExtensionRegistry} from './extensions.mjs';
export const extensions=createBrowserExtensionRegistry(definitions);
// One private registry per JS realm, shared by every editor module.
if(typeof window!=='undefined')window.afeExtensions=extensions;
export const resolveReference=(...args)=>extensions.first('resolveReference',...args)??null;
export const omitOwnedField=(...args)=>extensions.some('omitOwnedField',...args);
export const omitRecordField=(...args)=>extensions.some('omitRecordField',...args);
export const mediaRecordFor=(...args)=>extensions.first('mediaRecordFor',...args)??null;
export const imageSummary=(...args)=>extensions.first('imageSummary',...args);
export const mediaSource=(...args)=>extensions.first('mediaSource',...args);
export const mediaControl=(...args)=>extensions.first('mediaControl',...args);
export const siteChange=(...args)=>extensions.some('siteChange',...args);
export const mediaSelection=(...args)=>extensions.first('mediaSelection',...args)??null;
export const selectedMedia=(...args)=>extensions.first('selectedMedia',...args);
export const uploadedMediaId=(...args)=>extensions.first('uploadedMediaId',...args);
export const referencePrefix=(...args)=>extensions.first('referencePrefix',...args)??null;
export const optionalFieldAllowed=(...args)=>extensions.first('optionalFieldAllowed',...args);
export const referencedRecords=(...args)=>extensions.first('referencedRecords',...args);
export const siteWidgets=extensions.widgets;
export const mediaUsageKeys=new Set(extensions.first('mediaUsageKeys')||[]);
